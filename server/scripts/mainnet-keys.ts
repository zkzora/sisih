/**
 * Generate fresh mainnet keypairs for every demo role into .env.mainnet (gitignored).
 * Reuses no testnet key: every key is generated here. Refuses to overwrite an existing file.
 * Prints addresses only, never private keys.
 *   pnpm tsx scripts/mainnet-keys.ts
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Ed25519Keypair } from "@mysten/sui/keypairs/ed25519";

const ROOT = resolve(import.meta.dirname, "../..");
const OUT = resolve(ROOT, ".env.mainnet");
if (existsSync(OUT)) throw new Error(".env.mainnet already exists; refusing to overwrite mainnet keys");

const dotenv = Object.fromEntries(
  readFileSync(resolve(ROOT, ".env"), "utf8")
    .split(/\r?\n/)
    .filter((l) => l && !l.startsWith("#") && l.includes("="))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
);

const ROLES = [
  ["OWNER", "owner"],
  ["OPERATOR", "operator"],
  ["AGENT", "agent"],
  ["FACILITATOR", "facilitator"],
  ["PAYEE_INFERENCE", "payee Inference API (demo)"],
  ["PAYEE_HOSTING", "payee Hosting VPS (demo)"],
  ["PAYEE_SAVINGS", "payee Weekly savings (demo)"],
  ["PAYEE_DOMAIN", "payee Domain renewal (demo)"],
  ["MERCHANT_DATAMART", "merchant DataMart (demo)"],
  ["MERCHANT_SEARCHBOX", "merchant SearchBox (demo)"],
  ["MERCHANT_REPORTLAB", "merchant ReportLab (demo)"],
] as const;

const testnetKeys = new Set(Object.entries(dotenv).filter(([k]) => k.endsWith("_PRIVATE_KEY")).map(([, v]) => v));
const lines: string[] = [
  "# Sisih MAINNET demo keys, generated by server/scripts/mainnet-keys.ts. Gitignored.",
  "# Never commit, never upload to Vercel. Back this file up (password manager): it holds the only copy.",
  "SUI_NETWORK=mainnet",
  `TATUM_API_KEY_MAINNET=${dotenv.TATUM_API_KEY_MAINNET ?? ""}`,
  // Native USDC on Sui mainnet (Circle).
  "USDC_COIN_TYPE=0xdba34672e30cb065b1f93e3ab55318768fd6fef66c15942c9f7cb846e2f900e7::usdc::USDC",
  "SISIH_PACKAGE_ID=",
  "VAULT_ID=",
  "OPERATOR_CAP_ID=",
  "UPGRADE_CAP_ID=",
];
const table: string[] = [];
for (const [key, label] of ROLES) {
  const kp = Ed25519Keypair.generate();
  const sk = kp.getSecretKey();
  if (testnetKeys.has(sk)) throw new Error("generated key collides with a testnet key");
  lines.push(`${key}_PRIVATE_KEY=${sk}`);
  if (key.startsWith("MERCHANT_")) lines.push(`${key}_ADDRESS=${kp.toSuiAddress()}`);
  table.push(`${label.padEnd(30)} ${kp.toSuiAddress()}`);
}
lines.push(
  `MEMWAL_KEY=${dotenv.MEMWAL_KEY ?? ""}`,
  `MEMWAL_ACCOUNT_ID=${dotenv.MEMWAL_ACCOUNT_ID ?? ""}`,
  "MEMWAL_NAMESPACE=sisih-rehearsal",
  "MEMWAL_NAMESPACE_PREFIX=sisih-rehearsal",
  `DEMO_CYCLE_MS=${dotenv.DEMO_CYCLE_MS ?? "120000"}`,
  "DATABASE_URL=",
);
writeFileSync(OUT, lines.join("\n") + "\n", { mode: 0o600 });
console.log(`wrote ${OUT}\n`);
console.log(table.join("\n"));
